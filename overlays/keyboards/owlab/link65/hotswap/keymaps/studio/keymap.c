/* Live testing showed that the vendor bootloader does not enter DFU from
 * the generic STM32duino RTC flag. Do not advertise command entry. */
void mcu_reset(void) {
    NVIC_SystemReset();
}

bool via_command_kb(uint8_t *data, uint8_t length) {
    if (length != 32) return false;
    if (data[0] == 0x02 && data[1] == 0x7e) {
        memset(data + 2, 0, 30);
        memcpy(data + 2, "L65S", 4);
        data[6] = 1;    // Capability schema.
        data[7] = 1;    // Matrix reads. Update mode requires physical B + USB.
        raw_hid_send(data, length);
        return true;
    }
    if (data[0] == 0x02 && data[1] == 0x03) {
        uint8_t offset = data[2];
        memset(data + 3, 0, 29);
        for (uint8_t row = offset, p = 3; row < MATRIX_ROWS && p + 1 < length; row++, p += 2) {
            matrix_row_t value = matrix_get_row(row);
            data[p] = value >> 8;
            data[p + 1] = value & 0xff;
        }
        raw_hid_send(data, length);
        return true;
    }
    if (data[0] == 0x0b) {
        data[0] = 0xff;
        raw_hid_send(data, length);
        return true;
    }
    return false;
}

